-- Script de criacao do banco da Zato (Oracle)
-- Rodar no SQL Developer conectado na instancia da FIAP (F5 = executar script).
-- Os DROPs apagam as tabelas e sequences antigas. Se elas nao existirem,
-- o SQL Developer mostra erro nessas linhas e continua normalmente.

-- APAGAR ESTRUTURA ANTIGA
DROP TABLE T_TRANSACAO CASCADE CONSTRAINTS;
DROP TABLE T_CONTA_BANCARIA CASCADE CONSTRAINTS;
DROP TABLE T_META CASCADE CONSTRAINTS;
DROP TABLE T_DESEJO CASCADE CONSTRAINTS;
DROP TABLE T_USUARIO CASCADE CONSTRAINTS;

DROP SEQUENCE SEQ_USUARIO;
DROP SEQUENCE SEQ_CONTA_BANCARIA;
DROP SEQUENCE SEQ_TRANSACAO;
DROP SEQUENCE SEQ_META;
DROP SEQUENCE SEQ_DESEJO;

-- SEQUENCES (geram os IDs automaticos)
CREATE SEQUENCE SEQ_USUARIO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_CONTA_BANCARIA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TRANSACAO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_META START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_DESEJO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- USUARIO
CREATE TABLE T_USUARIO (
    ID_USUARIO    NUMBER PRIMARY KEY,
    NM_USUARIO    VARCHAR2(100) NOT NULL,
    DS_EMAIL      VARCHAR2(150) NOT NULL UNIQUE,
    DS_SENHA      VARCHAR2(255) NOT NULL,
    DT_CADASTRO   DATE DEFAULT SYSDATE
);

-- CONTA_BANCARIA
CREATE TABLE T_CONTA_BANCARIA (
    ID_CONTA      NUMBER PRIMARY KEY,
    ID_USUARIO    NUMBER NOT NULL,
    NM_BANCO      VARCHAR2(100) NOT NULL,
    TP_CONTA      VARCHAR2(20) NOT NULL,
    VL_SALDO      NUMBER(15,2) DEFAULT 0 NOT NULL,
    DS_COR        VARCHAR2(7),
    CONSTRAINT FK_CONTA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_USUARIO(ID_USUARIO)
);

-- TRANSACAO
CREATE TABLE T_TRANSACAO (
    ID_TRANSACAO  NUMBER PRIMARY KEY,
    ID_CONTA      NUMBER NOT NULL,
    DS_DESCRICAO  VARCHAR2(200) NOT NULL,
    VL_VALOR      NUMBER(15,2) NOT NULL,
    TP_TIPO       VARCHAR2(10) NOT NULL CHECK (TP_TIPO IN ('RECEITA','DESPESA')),
    DT_TRANSACAO  DATE DEFAULT SYSDATE NOT NULL,
    DS_CATEGORIA  VARCHAR2(50),
    CONSTRAINT FK_TRANSACAO_CONTA FOREIGN KEY (ID_CONTA) REFERENCES T_CONTA_BANCARIA(ID_CONTA)
);

-- META
CREATE TABLE T_META (
    ID_META       NUMBER PRIMARY KEY,
    ID_USUARIO    NUMBER NOT NULL,
    NM_META       VARCHAR2(100) NOT NULL,
    VL_OBJETIVO   NUMBER(15,2) NOT NULL,
    VL_ATUAL      NUMBER(15,2) DEFAULT 0 NOT NULL,
    DT_PRAZO      DATE,
    DS_STATUS     VARCHAR2(20),
    CONSTRAINT FK_META_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_USUARIO(ID_USUARIO)
);

-- DESEJO
CREATE TABLE T_DESEJO (
    ID_DESEJO     NUMBER PRIMARY KEY,
    ID_USUARIO    NUMBER NOT NULL,
    NM_PRODUTO    VARCHAR2(150) NOT NULL,
    VL_ESTIMADO   NUMBER(15,2),
    DS_LINK       VARCHAR2(500),
    DS_PRIORIDADE VARCHAR2(20) CHECK (DS_PRIORIDADE IN ('ALTA','MEDIA','BAIXA')),
    CONSTRAINT FK_DESEJO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_USUARIO(ID_USUARIO)
);
